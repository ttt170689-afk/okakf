  /* ============================================================
   * 3. ДВИЖОК ДИАЛОГОВ
   * ============================================================ */
  class DialogueEngine {
    constructor(game) {
      this.game = game;
      this.said = {};            // npcId -> Set текстов, сказанных недавно
      this.storyDone = new Set(); // завершённые главы
      this.pendingChoice = null;
    }

    /** Собрать контекст для предикатов */
    context() {
      const g = this.game;
      const h = g.gameHours % 24;
      return {
        hour: h,
        morning: h >= 5 && h < 11,
        evening: h >= 17 && h < 21,
        night: h >= 21 || h < 5,
        stage: g.furry.stage,
        relation: g.furry.relation,
        artyom: g.artyomRelation || 0,
        hunger: g.furry.hunger,
        mood: g.furry.mood,
        weather: g.weatherSys ? g.weatherSys.current : g.weather,
        day: g.day,
        questsDone: g.quests.done.size,
        ripped: g.clothing ? g.clothing.ripCount : 0,
        prestige: g.clothing ? g.clothing.bonuses().prestige : false,
        coins: g.inv.coins,
        shops: g.visited.size,
      };
    }

    /** Подобрать наиболее уместную реплику для NPC */
    pick(npcId) {
      const pool = CONTEXT_DIALOGUE[npcId];
      if (!pool || !pool.length) {
        const legacy = FF.DIALOGUE[npcId];
        return legacy ? U.pick(legacy.greet) : '...';
      }
      const ctx = this.context();
      const said = (this.said[npcId] = this.said[npcId] || new Set());

      // Отбираем подходящие, взвешиваем по специфичности
      const valid = [];
      for (const l of pool) {
        let ok = true;
        try { ok = !l.when || l.when(ctx); } catch (e) { ok = false; }
        if (!ok) continue;
        let w = l.score;
        if (said.has(l.text)) w *= 0.12;   // недавно говорили — почти не повторяем
        valid.push({ l, w });
      }
      if (!valid.length) return U.pick(pool).text;

      // Взвешенный выбор
      const total = valid.reduce((s, v) => s + v.w, 0);
      let r = Math.random() * total;
      for (const v of valid) { r -= v.w; if (r <= 0) { said.add(v.l.text); this._trim(said); return v.l.text; } }
      return valid[0].l.text;
    }

    _trim(set) {
      // Помним последние 6 реплик, чтобы не повторяться, но и не молчать вечно
      while (set.size > 6) set.delete(set.values().next().value);
    }

    /** Доступная глава сюжета Артёма (если есть) */
    availableChapter() {
      for (const ch of ARTYOM_STORY) {
        if (this.storyDone.has(ch.id)) continue;
        let ok = false;
        try { ok = ch.unlock(this.game); } catch (e) { ok = false; }
        if (ok) return ch;
        break;   // главы строго по порядку
      }
      return null;
    }

    /** Завершить главу и выдать награду */
    finishChapter(chapterId, choiceIndex) {
      const ch = ARTYOM_STORY.find((c) => c.id === chapterId);
      if (!ch || this.storyDone.has(chapterId)) return null;
      const g = this.game;
      const choice = ch.choices[choiceIndex] || ch.choices[0];
      this.storyDone.add(chapterId);
      g.artyomRelation = (g.artyomRelation || 0) + (choice.rel || 0);

      const r = ch.reward || {};
      let msg = `📖 ${ch.title} — завершена.`;
      if (r.coins) { g.inv.addCoins(r.coins); msg += ` +${r.coins}🪙`; }
      if (r.item) { g.inv.add(r.item, r.count || 1); msg += ` +${FF.ING_BY_ID[r.item].name}`; }
      if (r.recipe) { g.inv.elixirRecipes.add(r.recipe); msg += ' +рецепт эликсира'; }
      if (r.elixirRecipe) { g.inv.elixirRecipes.add(r.elixirRecipe); msg += ' +секретный рецепт'; }
      if (r.elixir) { g.inv.elixirs[r.elixir] = (g.inv.elixirs[r.elixir] || 0) + 1; msg += ' +эликсир'; }
      if (r.secret) g.secrets.add(r.secret);
      if (r.achievement) g.achieve(r.achievement);
      if (choice.startQuest) g.quests.accept(choice.startQuest);

      g.notify(msg, 'quest');
      g.audio.ui('achieve');
      if (g.artyomRelation >= 100) g.achieve('artyom_friend');
      return choice.reply;
    }

    serialize() { return { storyDone: [...this.storyDone] }; }
    deserialize(d) { if (d && d.storyDone) this.storyDone = new Set(d.storyDone); }
  }

  FF.CONTEXT_DIALOGUE = CONTEXT_DIALOGUE;
  FF.ARTYOM_STORY = ARTYOM_STORY;
  FF.DialogueEngine = DialogueEngine;
